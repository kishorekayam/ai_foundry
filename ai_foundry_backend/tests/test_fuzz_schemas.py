"""Property test: random, completely different schemas must generate with ZERO failed checks and load cleanly.

No schema is hand-written here. A seeded generator builds tables with random column types, primary keys (serial,
identity, uuid, text, composite, none), foreign keys (incl. one-to-one, self references, FK primary keys), unique
constraints (single, composite, unique indexes, partial, expression), CHECK ranges / IN lists, enum types, arrays,
JSON, generated columns, ...
"""
import random
import time

import psycopg
import pytest

from tests.test_user_connections import H1, api, body  # noqa: F401  (api fixture)

SCALARS = [
    "integer", "smallint", "bigint", "numeric(8,2)", "numeric(5,0)", "real", "double precision", "boolean",
    "varchar(3)", "varchar(12)", "varchar(50)", "varchar(120)", "char(3)", "text", "date", "timestamp", "timestamptz",
    "time", "uuid", "jsonb", "text[]", "integer[]", "inet", "bytea",
]
WORDS = ["alpha", "beta", "gamma", "delta", "status", "code", "label", "value", "kind", "name", "email", "notes", "price", "qty", "start_date", "end_date", "created_at", "updated_at", "country", "url", "phone"]


def build_schema(seed: int):
    rnd = random.Random(seed)
    sch = f"fz{seed}"
    ddl = [f"DROP SCHEMA IF EXISTS {sch} CASCADE", f"CREATE SCHEMA {sch}", f"CREATE TYPE {sch}.mood AS ENUM ('calm','happy','angry','sleepy')"]
    tables: list[dict] = []
    for ti in range(rnd.randint(5, 9)):
        name = f"t{ti}_{rnd.choice(WORDS)}"
        cols: list[str] = []
        used = set()
        info = {"name": name, "pk": None, "pk_type": None, "cols": {}}
        pk_kind = rnd.choice(["serial", "bigserial", "identity", "identity_always", "uuid", "text", "composite", "none"])
        if pk_kind == "serial":
            cols.append("id SERIAL PRIMARY KEY"); info.update(pk="id", pk_type="integer")
        elif pk_kind == "bigserial":
            cols.append("id BIGSERIAL PRIMARY KEY"); info.update(pk="id", pk_type="bigint")
        elif pk_kind == "identity":
            cols.append("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"); info.update(pk="id", pk_type="integer")
        elif pk_kind == "identity_always":
            cols.append("id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY"); info.update(pk="id", pk_type="integer")
        elif pk_kind == "uuid":
            cols.append("id UUID PRIMARY KEY DEFAULT gen_random_uuid()"); info.update(pk="id", pk_type="uuid")
        elif pk_kind == "text":
            cols.append("id VARCHAR(16) PRIMARY KEY"); info.update(pk="id", pk_type="varchar(16)")
        used.add("id")
        fk_cols: list[str] = []
        # foreign keys to earlier tables
        for _ in range(rnd.randint(0, 2) if tables else 0):
            ref = rnd.choice([t for t in tables if t["pk"]] or [None])
            if not ref:
                continue
            cn = f"{ref['name']}_ref{len(fk_cols)}"
            nullable = rnd.random() < 0.4
            uniq = " UNIQUE" if rnd.random() < 0.2 else ""
            cols.append(f"{cn} {ref['pk_type']}{'' if nullable else ' NOT NULL'}{uniq} REFERENCES {sch}.{ref['name']}({ref['pk']})")
            fk_cols.append(cn); used.add(cn)
        if info["pk"] and rnd.random() < 0.15:  # self reference
            cols.append(f"parent_id {info['pk_type']} REFERENCES {sch}.{name}({info['pk']})"); used.add("parent_id")
        if pk_kind == "composite" and len(fk_cols) >= 2:
            cols.append(f"PRIMARY KEY ({fk_cols[0]}, {fk_cols[1]})")
            for i in (0, 1):  # PK columns must be NOT NULL
                cols = [c.replace(f"{fk_cols[i]} ", f"{fk_cols[i]} ", 1) for c in cols]
        plain: list[tuple[str, str]] = []
        for ci in range(rnd.randint(2, 7)):
            t = rnd.choice(SCALARS)
            cn = f"c{ci}_{rnd.choice(WORDS)}"
            if cn in used:
                continue
            used.add(cn)
            parts = [f"{cn} {t}"]
            nn = rnd.random() < 0.6
            if nn:
                parts.append("NOT NULL")
            base = t.split("(")[0]
            if base in ("integer", "smallint", "bigint", "numeric", "real", "double precision") and rnd.random() < 0.3:
                lo = rnd.choice([0, 1, 5]); hi = lo + rnd.choice([10, 100, 250])
                parts.append(f"CHECK ({cn} BETWEEN {lo} AND {hi})" if rnd.random() < 0.5 else f"CHECK ({cn} >= {lo} AND {cn} <= {hi})")
            if base in ("varchar", "char", "text") and t not in ("varchar(3)", "char(3)") and rnd.random() < 0.2:
                parts.append(f"CHECK ({cn} IN ('red','green','blue','amber'))")
            if base in ("integer", "bigint", "varchar", "text", "uuid", "date", "timestamp", "timestamptz", "numeric") and rnd.random() < 0.12:
                parts.append("UNIQUE")
            cols.append(" ".join(parts))
            plain.append((cn, t))
        if rnd.random() < 0.15:
            cols.append(f"mood_col {sch}.mood{' NOT NULL' if rnd.random() < 0.5 else ''}"); used.add("mood_col")
        nums = [c for c, t in plain if t.split("(")[0] in ("integer", "bigint", "smallint", "numeric")]
        if nums and rnd.random() < 0.15:
            cols.append(f"gen_col numeric GENERATED ALWAYS AS ({nums[0]} * 2) STORED")
        # composite unique, unique indexes
        cand = [c for c in fk_cols] + [c for c, t in plain if t.split("(")[0] in ("integer", "smallint", "varchar", "char", "boolean", "date")]
        if len(cand) >= 2 and rnd.random() < 0.3:
            a, b = rnd.sample(cand, 2)
            cols.append(f"UNIQUE ({a}, {b})")
        ddl.append(f"CREATE TABLE {sch}.{name} ({', '.join(cols)})")
        txt = [c for c, t in plain if t.split("(")[0] in ("varchar", "text")]
        if txt and rnd.random() < 0.15:
            ddl.append(f"CREATE UNIQUE INDEX ON {sch}.{name} (lower({txt[0]}))")
        if txt and rnd.random() < 0.15:
            ddl.append(f"CREATE UNIQUE INDEX ON {sch}.{name} ({txt[-1]}) WHERE {txt[-1]} IS NOT NULL")
        info["cols"] = dict(plain)
        tables.append(info)
    return sch, ddl, [t["name"] for t in tables]


@pytest.mark.parametrize("seed", list(range(1, int(__import__("os").environ.get("FUZZ_MAX", "15")) + 1)))
def test_random_schema_zero_failures_and_loads(api, pg, seed):
    sch, ddl, names = build_schema(seed)
    with psycopg.connect(pg["uri"], autocommit=True) as c:
        for stmt in ddl:
            c.execute(stmt)
    cx = api.post("/api/connections/test", json=body(pg, schema=sch, label=f"fuzz{seed}"), headers=H1).json()
    assert cx["ok"] and cx["tablesDiscovered"] == len(names), (cx, ddl)
    schema = api.post("/api/schema", json={"targetId": cx["targetId"]}, headers=H1).json()
    rnd = random.Random(seed * 7919)
    counts = [{"table": n, "count": rnd.choice([0, 3, 8, 25, 60, 150])} for n in names]
    if not any(c["count"] for c in counts):
        counts[0]["count"] = 20
    jid = api.post("/api/jobs", json={"schema": schema, "config": {"mode": "fast", "locale": "en_US", "seed": seed, "tables": counts}}, headers=H1).json()["jobId"]
    while (j := api.get(f"/api/jobs/{jid}").json())["status"] == "running":
        time.sleep(0.2)
    assert j["status"] in ("completed", "partial"), (j.get("error"), j["report"]["checks"] if j.get("report") else None, ddl)
    failed = [(c["label"], c["detail"]) for c in j["report"]["checks"] if c["status"] == "failed"]
    assert not failed, (failed, ddl)
    if j["report"]["recordsGenerated"] == 0:
        return
    lid = api.post(f"/api/jobs/{jid}/load", json={"targetId": cx["targetId"], "approved": True}, headers=H1).json()["loadId"]
    for _ in range(400):
        ld = api.get(f"/api/loads/{lid}").json()
        if ld["status"] != "running":
            break
        time.sleep(0.2)
    assert ld["status"] == "success", (ld["error"], ld["verification"], [p for p in ld["perTable"] if p["inserted"] != p["expected"]], ddl)
